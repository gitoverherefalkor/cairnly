#!/usr/bin/env node
// Generates the outreach_prospects seed migration from the CSV.
//
//   node scripts/gen-outreach-seed.mjs
//
// Reads  supabase/seed/outreach_prospects_seed.csv  (the source of truth for
// which bureaus exist and which utm_content slug each one has) and writes
// supabase/migrations/20260909120100_outreach_prospects_seed.sql as one
// idempotent upsert on `slug`. Re-running the migration refreshes the seeded
// columns but never touches `status` or `notities`: those two are the only
// fields edited by hand in /ops, so a re-seed must not wipe them.
//
// Edit the CSV, re-run this script, apply the migration. Never hand-edit the
// generated SQL.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CSV = resolve(root, 'supabase/seed/outreach_prospects_seed.csv');
const OUT = resolve(root, 'supabase/migrations/20260909120100_outreach_prospects_seed.sql');

const COLUMNS = [
  'slug', 'naam', 'tier', 'categorie', 'to_email', 'domain', 'alt_domain',
  'contactpersoon', 'plaats', 'campaign', 'bow_slug', 'openingshaak',
];

/** Minimal RFC 4180 parser: quoted fields, doubled quotes, CRLF or LF. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else { quoted = false; }
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ',') {
      row.push(field); field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((v) => v !== '')) rows.push(row);
      row = [];
    } else {
      field += c;
    }
  }
  if (field !== '' || row.length) { row.push(field); if (row.some((v) => v !== '')) rows.push(row); }
  return rows;
}

const sqlLit = (v) => {
  const s = (v ?? '').trim();
  return s === '' ? 'null' : `'${s.replace(/'/g, "''")}'`;
};

const [header, ...records] = parseCsv(readFileSync(CSV, 'utf8').replace(/^﻿/, ''));
if (header.join(',') !== COLUMNS.join(',')) {
  throw new Error(`CSV header mismatch.\n  got:      ${header.join(',')}\n  expected: ${COLUMNS.join(',')}`);
}

const slugs = new Set();
for (const r of records) {
  const slug = r[0].trim();
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) throw new Error(`Bad slug: "${slug}"`);
  if (slugs.has(slug)) throw new Error(`Duplicate slug: ${slug}`);
  slugs.add(slug);
  if (!['A', 'B', 'C'].includes(r[2].trim())) throw new Error(`Bad tier for ${slug}: ${r[2]}`);
}

const values = records
  .map((r) => `  (${COLUMNS.map((_, i) => sqlLit(r[i])).join(', ')})`)
  .join(',\n');

const updates = COLUMNS.filter((c) => c !== 'slug')
  .map((c) => `  ${c} = excluded.${c}`)
  .join(',\n');

const sql = `-- GENERATED by scripts/gen-outreach-seed.mjs from
-- supabase/seed/outreach_prospects_seed.csv. Do not hand-edit: change the
-- CSV and re-run the script.
--
-- Seeds the ${records.length} outreach prospects (bureaus) for the click-tracking
-- dashboard. Idempotent: upserts on slug. The two hand-edited columns
-- (status, notities) are deliberately NOT in the update list so a re-seed
-- never overwrites work done in /ops.

insert into public.outreach_prospects
  (${COLUMNS.join(', ')})
values
${values}
on conflict (slug) do update set
${updates},
  updated_at = now();
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${records.length} prospects)`);
